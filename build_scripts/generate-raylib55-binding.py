#!/usr/bin/env python3
"""FreeBASIC JS SDK: translate the raylib 5.5 public API to raylib55.bi.

Run against parser/output/raylib_api.json from the pinned raylib source.
This file translates declarations. Library selection lives in the binding
and the platform's compiler driver.
"""

import argparse
import json
import re
from pathlib import Path


C_TYPES = {
    "void": "any", "bool": "ubyte", "char": "zstring",
    "int": "long", "unsigned int": "ulong", "unsigned char": "ubyte",
    "unsigned short": "ushort", "float": "single", "double": "double",
}


def fb_type(c_type):
    base = c_type.split("*")[0].strip()
    const = base.startswith("const ")
    base = base.removeprefix("const ")
    pointers = c_type.count("*")
    # Text uses ZString through pointers. A scalar C char is a byte.
    translated = "byte" if base == "char" and not pointers else C_TYPES.get(base, base)
    return ("const " if const else "") + translated + " ptr" * pointers


def signature(entry):
    params = ", ".join("..." if p["type"] == "..." else "byval as " + fb_type(p["type"])
                       for p in entry.get("params", []))
    result = entry["returnType"]
    kind = "sub" if result == "void" else "function"
    suffix = "" if result == "void" else " as " + fb_type(result)
    return kind, params, suffix


def write_binding(api, license_text, target):
    lines = [
        "'' Project: FreeBASIC raylib binding",
        "'' File: raylib55.bi",
        "'' Purpose: Declare the raylib 5.5 C API and its binary data layouts.",
        "'' Responsibilities: Public types, callbacks, constants and entry points.",
        "'' This file intentionally does not contain raylib or platform implementations.",
        "''",
        "'' Generated by build_scripts/generate-raylib55-binding.py from raylib 5.5.",
        "'' This translation is an altered version of the upstream declarations.",
        "''",
        *("'' " + line.rstrip() if line.strip() else "''" for line in license_text.splitlines()),
        "",
        "#pragma once",
        '#inclib "raylib"',
        "#ifndef __FB_JS__",
        "#if defined(__FB_WIN32__)",
        '\t#inclib "opengl32"',
        '\t#inclib "gdi32"',
        '\t#inclib "winmm"',
        "#elseif defined(__FB_LINUX__)",
        '\t#inclib "GL"',
        '\t#inclib "X11"',
        '\t#inclib "pthread"',
        '\t#inclib "dl"',
        '\t#inclib "rt"',
        '\t#inclib "m"',
        "#elseif defined(__FB_DARWIN__)",
        '\t#inclib "OpenGL"',
        '\t#inclib "Cocoa"',
        '\t#inclib "IOKit"',
        '\t#inclib "CoreVideo"',
        "#endif",
        "#endif",
        '#include once "crt/stdarg.bi"',
        '#include once "crt/stdlib.bi"',
        "",
        'extern "C"',
        "",
        "'' The audio device owns these opaque objects. Only pointers cross the API.",
        "type rAudioBuffer as rAudioBuffer_",
        "type rAudioProcessor as rAudioProcessor_",
        "",
    ]

    for define in api["defines"]:
        name, kind, value = (define[key] for key in ("name", "type", "value"))
        if kind == "COLOR":
            components = re.search(r"\{([^}]+)\}", value).group(1).strip()
            lines.append(f"#define {name} type<Color>({components})")
        elif kind in ("INT", "FLOAT", "FLOAT_MATH", "STRING"):
            if kind == "STRING":
                value = json.dumps(value)
            lines.append(f"#define {name} {value}")
        elif name.startswith(("RL_MALLOC(", "RL_CALLOC(", "RL_REALLOC(", "RL_FREE(")):
            lines.append(f"#define {name} {value}")
        elif kind == "UNKNOWN" and name != "RLAPI":
            lines.append(f"#define {name} {value}")
    lines.append("")

    for entry in api["structs"]:
        name = entry["name"]
        lines.extend((f"'' {entry['description']}", f"type {name}"))
        for field in entry["fields"]:
            c_type = field["type"]
            field_name = field["name"]
            extent = re.fullmatch(r"(.*)\[(\d+)\]", c_type)
            if extent:
                c_type, count = extent.groups()
                field_name += f"(0 to {int(count) - 1})"
            lines.append(f"\t{field_name} as {fb_type(c_type)}")
        lines.extend(("end type", ""))
        for alias in api["aliases"]:
            if alias["type"] == name:
                lines.extend((f"type {alias['name']} as {name}", ""))

    for entry in api["enums"]:
        name = entry["name"]
        lines.extend((f"'' {entry['description']}", f"type {name} as long", "enum"))
        for value in entry["values"]:
            lines.append(f"\t{value['name']} = {value['value']}")
        lines.extend(("end enum", ""))

    for entry in api["callbacks"]:
        kind, params, suffix = signature(entry)
        lines.append(f"type {entry['name']} as {kind} cdecl({params}){suffix}")
    lines.extend(("", "'' Public raylib entry points", ""))

    for entry in api["functions"]:
        kind, params, suffix = signature(entry)
        lines.append(f"declare {kind} {entry['name']}({params}){suffix}")

    lines.extend(("", "end extern", "", "'' end of raylib55.bi", ""))
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="raylib 5.5 source directory")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    api = json.loads((args.source / "parser/output/raylib_api.json").read_text(encoding="utf-8"))
    version = next(entry["value"] for entry in api["defines"] if entry["name"] == "RAYLIB_VERSION")
    if version != "5.5":
        parser.error(f"expected raylib 5.5, found {version}")
    write_binding(api, (args.source / "LICENSE").read_text(encoding="utf-8"), args.output)

# end of generate-raylib55-binding.py
