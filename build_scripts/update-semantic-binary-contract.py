#!/usr/bin/env python3
"""Project: FreeBASIC compiler tooling
File: update-semantic-binary-contract.py
Purpose: Generate binary element definitions from the documented semantic table.
Responsibilities: Keep compiler and vendored linter vocabularies in agreement.
This file intentionally does NOT change semantic schemas or generate lint rules.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re


def generate(root: Path) -> bytes:
    documentation = (root / "doc/compiler-semantic-model.md").read_text(encoding="utf-8")
    rows = re.findall(r"^\| `([A-Z]+)` \| (.*?) \| (\d+) \|", documentation, re.M)
    if not rows or len({tag for tag, _, _ in rows}) != len(rows) or len(rows) > 255:
        raise ValueError("Invalid or repeated semantic element definitions")
    lines = [
        "'' Project: FreeBASIC semantic binary contract",
        "'' File: fbc-semantic-elements.bi",
        "'' Purpose: Name the binary tags and describe their semantic fields.",
        "'' Responsibilities: Keep the producer and consumer record vocabulary identical.",
        "'' Targets: Native FreeBASIC compiler and linter host builds; linted targets use",
        "'' the compiler's target options.",
        "'' Module API: Private helpers FbcSemElements() and FbcSemElementId().",
        "'' This file intentionally does NOT contain:",
        "''     - language parsing or semantic policy, which belong to the consumers.",
        "'' Generated by build_scripts/update-semantic-binary-contract.py from the record table.",
        "#ifndef FBC_SEMANTIC_ELEMENTS_BI", "#define FBC_SEMANTIC_ELEMENTS_BI", "",
        "private function FbcSemElements() as string", "\tdim as string result",
    ]
    for identity, (tag, description, count) in enumerate(rows, 1):
        description = description.replace('"', '""')
        lines.append(f'\tresult += "record" + chr(9) + "{identity}" + chr(9) + "{tag}" + '
                     f'chr(9) + "{count}" + chr(9) + "{description}" + chr(10)')
    lines += ["\treturn result", "end function", "",
              "private function FbcSemElementId(byref tag as const string) as integer", "\tselect case tag"]
    lines += [f'\tcase "{tag}": return {identity}' for identity, (tag, _, _) in enumerate(rows, 1)]
    lines += ["\tend select", "\treturn 0", "end function", "", "#endif",
              "'' end of fbc-semantic-elements.bi", ""]
    return "\n".join(lines).encode("ascii")


def validate_symbol_identity_limits(root: Path, linter_root: Path) -> None:
    compiler = (root / "src/compiler/tooling/semantic-model.bas").read_text(encoding="utf-8")
    linter = (linter_root / "src/fb_linter_semantic.bi").read_text(encoding="utf-8")
    documentation = (root / "doc/compiler-semantic-model.md").read_text(encoding="utf-8")
    producer_match = re.search(
        r"^private const SEMANTIC_MODEL_MAX_SYMBOL_IDENTITIES = (\d+)\s*$",
        compiler, re.M)
    consumer_match = re.search(
        r"^Const FBLINT_MAX_SEMANTIC_MODEL_IDENTITIES As LongInt = (\d+)\s*$",
        linter, re.M)
    symbol_alias_matches = re.search(
        r"^Const FBLINT_MAX_SEMANTIC_SYMBOL_TYPES As LongInt = "
        r"FBLINT_MAX_SEMANTIC_MODEL_IDENTITIES\s*$", linter, re.M)
    documented_match = re.search(
        r"model-wide symbol identity IDs to ([0-9,]+) per model", documentation)
    if not producer_match or not consumer_match or not symbol_alias_matches or not documented_match:
        raise ValueError("Missing or inconsistent model-wide symbol identity limits")
    producer_limit = int(producer_match.group(1))
    if (producer_limit != int(consumer_match.group(1)) or
            producer_limit != int(documented_match.group(1).replace(",", ""))):
        raise ValueError("Compiler, linter, and documentation symbol identity limits differ")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--linter-root", type=Path)
    parser.add_argument("--write", action="store_true", help="Regenerate the definition and optional vendored copies")
    options = parser.parse_args()
    root = options.root.resolve()
    generated = generate(root)
    if options.linter_root:
        validate_symbol_identity_limits(root, options.linter_root.resolve())
    targets = [(root / "inc/fbc-semantic-elements.bi", generated)]
    if options.linter_root:
        targets.append((options.linter_root / "src/fbc-semantic-elements.bi", generated))
        targets.append((options.linter_root / "src/fbc-semantic-binary.bi",
                        (root / "inc/fbc-semantic-binary.bi").read_bytes()))
        targets.append((options.linter_root / "docs/compiler-semantic-model.md",
                        (root / "doc/compiler-semantic-model.md").read_bytes()))
    for path, expected in targets:
        if options.write:
            if not path.is_file() or path.read_bytes() != expected:
                path.write_bytes(expected)
        elif not path.is_file() or path.read_bytes() != expected:
            raise SystemExit("Semantic binary contract differs: " + str(path))
    print("SEMANTIC_BINARY_CONTRACT_MATCH")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

