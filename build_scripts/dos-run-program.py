#!/usr/bin/env python3
"""FreeBASIC DOS qualification: dos-run-program.py.

Run one DOS executable with fresh guest receipts, a time limit and output caps.
This module owns emulator process control; it does not build or select tests.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time


def dos_argument(value: str) -> str:
    # COMMAND.COM parses the generated batch before the executable sees argv.
    # Reject expansion, redirection and control syntax rather than escaping it
    # differently across DOSBox-X shell versions.
    if not value or any(c in value for c in '\r\n"%&|<>^'):
        raise ValueError(f'unsupported DOS command argument: {value!r}')
    return f'"{value}"' if ' ' in value else value


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def run(args: argparse.Namespace) -> int:
    package = args.package.resolve(strict=True)
    work = args.workdir.resolve(strict=True)
    emulator = args.dosbox.resolve(strict=True)
    if not re.fullmatch(r'[A-Za-z0-9_-]{1,8}\.exe', args.program, re.I):
        raise ValueError('--program must name an executable in 8.3 format')
    program = work / args.program
    if not program.is_file():
        raise ValueError(f'missing DOS executable: {program}')
    if not (package / 'djgpp/bin/CWSDPMI.EXE').is_file():
        raise ValueError(f'missing packaged CWSDPMI under {package}')
    if args.timeout <= 0 or args.max_output_bytes <= 0:
        raise ValueError('timeout and output limit must be positive')

    batch = work / 'FBCIRUN.BAT'
    owner = 'rem Generated by build_scripts/dos-run-program.py'
    if batch.exists() and owner not in batch.read_text(encoding='ascii'):
        raise ValueError(f'refusing to overwrite unrelated batch file: {batch}')
    output = work / 'FBCIRUN.OUT'
    status = work / 'FBCIRUN.RC'
    log = work / 'FBCIRUN.LOG'
    watched = [output, log]
    for name in args.watch_file:
        if not re.fullmatch(r'[A-Za-z0-9_-]+\.[A-Za-z0-9]+', name):
            raise ValueError('--watch-file must name a file in the work directory')
        watched.append(work / name)
    for path in (output, status, *watched[2:]):
        path.unlink(missing_ok=True)
    command_tail = ' '.join([args.program, *(dos_argument(x) for x in args.arg)])
    # DOS EXEC has a short command tail even when the host supports long argv.
    if len(command_tail.encode('ascii')) > 120:
        raise ValueError('DOS command tail exceeds 120 bytes; use a response file')
    batch.write_bytes(('\r\n'.join([
        '@echo off', owner,
        'set DJGPP=C:\\DJGPP\\DJGPP.ENV',
        'set PATH=C:\\FB;C:\\DJGPP\\BIN;Z:\\',
        # CWSDPMI otherwise creates its swap file on the package's C drive.
        # Keep runtime paging in this invocation's private work directory.
        'C:\\DJGPP\\BIN\\CWSDPMI.EXE -p -sD:\\FBCISWAP.SWP > D:\\FBCIRUN.OUT',
        command_tail + ' >> D:\\FBCIRUN.OUT',
        'if errorlevel 1 goto failed',
        'echo PASS > D:\\FBCIRUN.RC', 'goto done',
        ':failed', 'echo FAIL > D:\\FBCIRUN.RC', ':done',
        'C:\\DJGPP\\BIN\\CWSDPMI.EXE -u >> D:\\FBCIRUN.OUT',
        'rem end of FBCIRUN.BAT', '',
    ])).encode('ascii'))

    command = [str(emulator), '-fastlaunch', '-nogui', '-nomenu', '-exit',
               '-set', f'dosbox memsize={args.memory}',
               '-set', 'dos ver=7.1', '-set', 'dos lfn=true',
               '-set', 'cpu cputype=pentium_ii',
               '-set', f'cpu core={args.core}', '-set', 'cpu cycles=max',
               '-c', f'mount c "{package}"', '-c', f'mount d "{work}"',
               '-c', 'd:', '-c', 'FBCIRUN.BAT', '-c', 'exit']
    env = os.environ.copy()
    env.update(SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy')
    started = time.monotonic()
    reason = ''
    with log.open('wb') as stream:
        process = subprocess.Popen(command, env=env, stdout=stream, stderr=stream)
        try:
            while process.poll() is None:
                if time.monotonic() - started > args.timeout:
                    reason = 'timeout'
                if any(p.exists() and p.stat().st_size > args.max_output_bytes
                       for p in watched):
                    reason = 'output-limit'
                if reason:
                    process.kill()
                    break
                time.sleep(0.1)
        finally:
            if process.poll() is None:
                process.kill()
            process.wait()
    if any(p.exists() and p.stat().st_size > args.max_output_bytes for p in watched):
        reason = 'output-limit'
    marker = status.read_text(encoding='ascii').strip() if status.exists() else ''
    passed = not reason and process.returncode == 0 and marker == 'PASS'
    receipt = {
        'program': args.program, 'program_sha256': sha256(program),
        'emulator': str(emulator), 'emulator_sha256': sha256(emulator), 'core': args.core,
        'elapsed_seconds': round(time.monotonic() - started, 3),
        'emulator_exit': process.returncode, 'guest_status': marker,
        'stop_reason': reason, 'passed': passed,
        'output_bytes': output.stat().st_size if output.exists() else 0,
    }
    (work / 'FBCIRUN.JSON').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt), flush=True)
    if output.exists():
        # Console receipts remain bounded even when the guest hits its cap.
        with output.open('rb') as stream:
            print(stream.read(32768).decode('cp437', errors='replace'), flush=True)
    return 0 if passed else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dosbox', type=Path, required=True)
    parser.add_argument('--package', type=Path, required=True)
    parser.add_argument('--workdir', type=Path, required=True)
    parser.add_argument('--program', required=True)
    parser.add_argument('--arg', action='append', default=[])
    parser.add_argument('--timeout', type=float, default=300)
    parser.add_argument('--max-output-bytes', type=int, default=2 * 1024 * 1024)
    parser.add_argument('--watch-file', action='append', default=[],
                        help='additional fresh guest output to include in the size cap')
    # Older dynamic cores miscompile x87 comparisons on Pentium II. Use the
    # interpreter for correctness gates, regardless of host installation defaults.
    parser.add_argument('--core', choices=('normal', 'dynamic_x86'), default='normal')
    parser.add_argument('--memory', type=int, default=128)
    return run(parser.parse_args())


if __name__ == '__main__':
    raise SystemExit(main())

# end of dos-run-program.py
