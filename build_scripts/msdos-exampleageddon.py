#!/usr/bin/env python3
"""FreeBASIC DOS Exampleageddon; msdos-exampleageddon.py.

Compile the complete shared inventory with the packaged DOS compiler, execute
its runnable entries, and retain fresh, bounded receipts. Owns DOS batch/process
control; classification and source/resource layout remain in the shared runner.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


ROOT = Path(__file__).resolve().parents[1]
shared = load('dos_example_shared', ROOT / 'build_scripts/exampleageddon-freebasic.py')
guest = load('dos_program_shared', ROOT / 'build_scripts/dos-run-program.py')


def fingerprint(root: Path) -> str:
    """Bind resume receipts to all files in an input tree, including resources."""
    digest = hashlib.sha256()
    for path in sorted(root.rglob('*')):
        if path.is_file():
            digest.update(path.relative_to(root).as_posix().encode('utf-8') + b'\0')
            digest.update(guest.sha256(path).encode('ascii') + b'\0')
    return digest.hexdigest()


def read_rows(batch: Path, entries: list[dict]) -> dict[str, list[str]]:
    expected = {item['id']: item for item in entries}
    result = {}
    path = batch / 'RESULT.TSV'
    if not path.exists():
        return result
    for line in path.read_text(encoding='ascii').splitlines():
        row = line.split('\t')
        if len(row) != 6 or row[0] not in expected or row[0] in result:
            raise ValueError(f'invalid, extra or duplicate DOS result row: {line!r}')
        if row[1] != expected[row[0]]['group']:
            raise ValueError(f'changed classification in DOS result: {line!r}')
        if row[2] not in ('0', '1', 'timeout', 'output-limit'):
            raise ValueError(f'invalid compile status: {line!r}')
        if row[3] not in ('present', 'missing') or row[4] not in ('0', '1', 'not-run', 'timeout', 'output-limit'):
            raise ValueError(f'invalid artifact/run status: {line!r}')
        result[row[0]] = row
    return result


def quoted_path(value: str) -> str:
    return guest.dos_argument(value.replace('/', '\\'))


def log_name(ident: str, phase: str) -> str:
    # Shell-created logs must also use 8.3 names, even with DJGPP LFN enabled.
    suffix = {'compile': 'C', 'run': 'R', 'dep-fbc': 'F', 'dep-cxx': 'X',
              'dep-ar': 'A', 'dep-data': 'D'}[phase]
    return ident + suffix + '.LOG'


def redirected(command: str, log: str) -> str:
    # DOSBox-X's COMMAND.COM does not implement the Unix/CMD 2>&1 syntax.
    # Its native stdout redirection preserves the executable's errorlevel.
    # The packaged DJGPP redir utility misparses options with LFN enabled;
    # do not introduce that dependency into the compiler qualification path.
    result = f'{command} > {quoted_path(log)}'
    if len(result.encode('ascii')) > 120:
        raise ValueError(f'DOS command tail exceeds the safe limit: {result}')
    return result


def batch_starts(count: int, size: int, first: int) -> list[int]:
    """Prioritize a batch without dropping or duplicating inventory entries."""
    starts = list(range(0, count, size))
    if not 0 <= first < len(starts):
        raise ValueError('start batch is outside the example inventory')
    return starts[first:] + starts[:first]


def prepare_batch(batch: Path, entries: list[dict], args) -> None:
    for folder in ('WORK', 'BIN', 'LOG', 'TMP'):
        (batch / folder).mkdir(parents=True, exist_ok=True)
    rows = read_rows(batch, entries)
    lines = [
        '@echo off', 'rem FreeBASIC DOS Exampleageddon; RUNBATCH.BAT.',
        'rem Generated by build_scripts/msdos-exampleageddon.py.',
        'set DJGPP=C:\\DJGPP\\DJGPP.ENV', 'set LFN=y',
        'set GCC=C:\\DJGPP\\BIN\\GCC.EXE', 'set AS=C:\\DJGPP\\BIN\\AS.EXE',
        'set AR=C:\\DJGPP\\BIN\\AR.EXE', 'set LD=C:\\DJGPP\\BIN\\LD.EXE',
        'set PATH=C:\\FB;C:\\DJGPP\\BIN;Z:\\',
        'set FB_GFX_DRIVER=none', 'set SFXLIB_DRIVER=null',
        # -s must be the final CWSDPMI argument. Its default C: swap file
        # would mutate the compiler package and invalidate resume fingerprints.
        'C:\\DJGPP\\BIN\\CWSDPMI.EXE -p -sD:\\TMP\\CWSDPMI.SWP > D:\\LOG\\CWSDPMI.LOG',
    ]

    def dos(path: Path) -> str:
        return 'D:/' + path.relative_to(batch).as_posix()

    for item in entries:
        ident, rel = item['id'], item['path']
        if ident in rows:
            continue
        source = args.root / shared.INCLUDED_SOURCE_OWNERS.get(rel, rel)
        work_root = batch / 'WORK' / ident
        compile_cwd, run_cwd, _, copy_directories = shared.stage_example(source, args.root, rel, work_root)
        if item['runnable']:
            shared.prepare_run_directory(source.parent, run_cwd, copy_directories)
        artifact = batch / 'BIN' / (ident + '.EXE')
        base = ['-target', 'dos', '-arch', '686', '-fpu', 'x87', '-gen', 'gcc',
                '-w', 'all', '-exx', '-prefix', 'C:/FB', '-i', 'C:/FB/inc',
                '-p', 'C:/FB/lib/dos', '-i', dos(compile_cwd), '-p', dos(compile_cwd)]
        if args.sdk:
            base += ['-i', 'G:/include', '-p', 'G:/lib']
        flags = list(shared.EXAMPLE_FBC_ARGUMENTS.get(rel, ()))
        if rel == 'examples/graphics/SDL3/ttf/showfont.bas':
            flags += ['-m', 'showfont']
        module = shared.LIBRARY_MODULES.get(rel)
        local_lib = shared.LOCAL_LIBRARIES.get(rel)
        local_cpp = shared.LOCAL_CPP_LIBRARIES.get(rel)
        has_dependency = bool(local_lib or local_cpp or rel.endswith('/embed-access-data-in-executable.bas'))
        dependency = '0' if has_dependency else 'not-applicable'
        lines += [f'cd {quoted_path(dos(compile_cwd))}',
                  'set TMPDIR=' + dos(compile_cwd).replace('/', '\\'),
                  'set TEMP=' + dos(compile_cwd).replace('/', '\\'),
                  'set TMP=' + dos(compile_cwd).replace('/', '\\')]

        def step(executable: str, arguments: list[str], phase: str, failure: str) -> None:
            index = sum(1 for name in (batch / 'TMP').glob(ident + '*.RSP'))
            response = batch / 'TMP' / f'{ident}{index}.RSP'
            # Both FBC and GNU DOS tools accept quoted response-file arguments.
            # Keep the actual EXEC command well below DOS's command-tail limit.
            encoded = '\n'.join(guest.dos_argument(str(value)) for value in arguments) + '\n'
            response.write_text(encoded, encoding='ascii', newline='\n')
            log = 'D:/LOG/' + log_name(ident, phase)
            lines.extend([
                f'echo {ident}\t{phase}\t{item["group"]} > D:\\CURRENT.TSV',
                redirected(f'{quoted_path(executable)} @{quoted_path(dos(response))}', log),
                f'if errorlevel 1 goto {failure}{ident}',
            ])

        if local_lib:
            mode, name, sources, extra = local_lib
            output = compile_cwd / (name + '.dxe' if mode == '-dll' else 'lib' + name + '.a')
            step('C:/FB/FBC.EXE', base + flags + [mode, *extra,
                 *(dos(compile_cwd / name) for name in sources), '-x', dos(output)], 'dep-fbc', 'D')
        if local_cpp:
            step('C:/DJGPP/BIN/GXX.EXE', ['-c', local_cpp + '.cxx', '-o', local_cpp + '.o'], 'dep-cxx', 'D')
            step('C:/DJGPP/BIN/AR.EXE', ['rcs', 'lib' + local_cpp + '.a', local_cpp + '.o'], 'dep-ar', 'D')
            flags += ['-l', 'stdc++']
        if rel == 'examples/manual/proguide/embed-access-data-in-executable.bas':
            (compile_cwd / 'hello.txt').write_text('Hello from embedded data.\n', encoding='ascii')
            step('C:/DJGPP/BIN/LD.EXE', ['-r', '-b', 'binary', '-o', 'hello_txt.o', 'hello.txt'], 'dep-data', 'D')
            flags += [dos(compile_cwd / 'hello_txt.o')]
        if module:
            mode, extra = module
            artifact = artifact.with_suffix('.A' if mode == '-lib' else '.DXE')
            flags += [mode, *extra]
        # An interrupted compile can leave its old output in BIN. Require a
        # new product for every unrecorded case, including resumed batches.
        artifact.unlink(missing_ok=True)
        item['artifact'] = artifact.relative_to(batch).as_posix()
        inputs = [dos(path) for path in shared.compile_inputs(source, args.root, compile_cwd)]
        step('C:/FB/FBC.EXE', base + flags + inputs + ['-x', dos(artifact)], 'compile', 'C')
        lines.append(f'if not exist {quoted_path(dos(artifact))} goto A{ident}')

        def result(compile_status: str, present: str, run_status: str, dep: str) -> str:
            return f'echo {ident}\t{item["group"]}\t{compile_status}\t{present}\t{run_status}\t{dep} >> D:\\RESULT.TSV'

        if item['runnable']:
            run_arguments = ' '.join(guest.dos_argument(x) for x in shared.EXAMPLE_RUN_ARGUMENTS.get(rel, ()))
            if len(run_arguments.encode('ascii')) > 100:
                raise ValueError(f'DOS example run arguments exceed command tail: {rel}')
            lines += [f'echo {ident}\trun\t{item["group"]} > D:\\CURRENT.TSV',
                      f'cd {quoted_path(dos(run_cwd))}',
                      redirected(f'{quoted_path(dos(artifact))} {run_arguments}', 'D:/LOG/' + log_name(ident, 'run')),
                      f'if errorlevel 1 goto R{ident}',
                      result('0', 'present', '0', dependency), f'goto N{ident}',
                      f':R{ident}', result('0', 'present', '1', dependency)]
        else:
            lines.append(result('0', 'present', 'not-run', dependency))
        lines += [f'goto N{ident}', f':D{ident}', result('1', 'missing', 'not-run', '1'),
                  f'goto N{ident}', f':C{ident}', result('1', 'missing', 'not-run', dependency),
                  f'goto N{ident}', f':A{ident}', result('0', 'missing', 'not-run', dependency),
                  f':N{ident}', 'del D:\\CURRENT.TSV']
    lines += ['C:\\DJGPP\\BIN\\CWSDPMI.EXE -u >> D:\\LOG\\CWSDPMI.LOG',
              f'echo DONE={len(entries)} > D:\\DONE.TXT', 'rem end of RUNBATCH.BAT', '']
    (batch / 'RUNBATCH.BAT').write_bytes('\r\n'.join(lines).encode('ascii'))


def execute_batch(batch: Path, entries: list[dict], args) -> dict[str, list[str]]:
    attempts = 0
    while True:
        prepare_batch(batch, entries, args)
        (batch / 'DONE.TXT').unlink(missing_ok=True)
        (batch / 'CURRENT.TSV').unlink(missing_ok=True)
        command = [str(args.dosbox), '-fastlaunch', '-nogui', '-nomenu', '-exit',
                   '-set', 'dosbox memsize=128', '-set', 'dos ver=7.1', '-set', 'dos lfn=true',
                   '-set', 'cpu cputype=pentium_ii', '-set', f'cpu core={args.core}',
                   '-set', 'cpu cycles=max', '-c', f'mount c "{args.package}"',
                   '-c', f'mount d "{batch}"']
        if args.sdk:
            command += ['-c', f'mount g "{args.sdk}"']
        command += ['-c', 'd:', '-c', 'RUNBATCH.BAT', '-c', 'exit']
        env = os.environ.copy()
        env.update(SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy')
        current = None
        idle_started = time.monotonic()
        phase_started = time.monotonic()
        stopped = ''
        log = batch / f'dosbox-{attempts:02d}.log'
        with log.open('wb') as stream:
            process = subprocess.Popen(command, env=env, stdout=stream, stderr=stream)
            try:
                while process.poll() is None:
                    try:
                        marker = (batch / 'CURRENT.TSV').read_text(encoding='ascii').strip().split('\t')
                    except (OSError, UnicodeError):
                        marker = []
                    if len(marker) == 3:
                        idle_started = time.monotonic()
                        if marker != current:
                            current, phase_started = marker, time.monotonic()
                        limit = args.run_timeout if marker[1] == 'run' else args.compile_timeout
                        if marker[1] == 'run' and marker[2] == 'long-running-benchmark':
                            limit = max(limit, 900)
                        if time.monotonic() - phase_started > limit:
                            stopped = 'timeout'
                        if any(p.stat().st_size > args.max_output_bytes for p in (batch / 'LOG').glob(marker[0] + '*.LOG')):
                            stopped = 'output-limit'
                    elif time.monotonic() - idle_started > 60:
                        stopped = 'session-idle-timeout'
                    if log.stat().st_size > args.max_output_bytes * 4:
                        stopped = 'emulator-output-limit'
                    if stopped:
                        process.kill()
                        break
                    time.sleep(0.1)
            finally:
                if process.poll() is None:
                    process.kill()
                process.wait()
        rows = read_rows(batch, entries)
        if not stopped:
            marker = (batch / 'DONE.TXT').read_text().strip() if (batch / 'DONE.TXT').exists() else ''
            if process.returncode != 0 or marker != f'DONE={len(entries)}' or len(rows) != len(entries):
                raise RuntimeError(f'incomplete DOS batch {batch.name}: {len(rows)}/{len(entries)} rows, {marker!r}; inspect {log}')
            # A fast writer can exceed the cap and exit between monitor ticks.
            # Check every final log as well, preserving any actual run result.
            for ident, row in rows.items():
                for path in (batch / 'LOG').glob(ident + '*.LOG'):
                    if path.stat().st_size > args.max_output_bytes:
                        if path.name == log_name(ident, 'run'):
                            row[4] = 'output-limit'
                        else:
                            row[2] = 'output-limit'
            (batch / 'RESULT.TSV').write_text(''.join('\t'.join(row) + '\n' for row in rows.values()), encoding='ascii', newline='')
            return rows
        if stopped not in ('timeout', 'output-limit') or current is None:
            raise RuntimeError(f'DOS batch infrastructure failed: {stopped}; inspect {log}')
        ident, phase, group = current
        if ident not in {item['id'] for item in entries}:
            raise RuntimeError(f'unknown active example: {current}')
        if ident not in rows:
            row = [ident, group, '0' if phase == 'run' else stopped,
                   'present' if phase == 'run' else 'missing',
                   stopped if phase == 'run' else 'not-run', 'unknown']
            with (batch / 'RESULT.TSV').open('a', encoding='ascii', newline='') as output:
                output.write('\t'.join(row) + '\n')
        print(f'{batch.name} {ident} {phase} {stopped}; continuing remaining examples', flush=True)
        attempts += 1
        if attempts > len(entries):
            raise RuntimeError('DOS batch exhausted its bounded restart count')


def write_reports(entries: list[dict], records: dict, args) -> bool:
    results = []
    for item in entries:
        row = records.get(item['id'])
        compile_status, run_status = 'pending', 'pending'
        if row:
            compile_status = 'pass' if row[2] == '0' and row[3] == 'present' else 'fail(' + row[2] + '-' + row[3] + ')'
            run_status = 'pass' if row[4] == '0' else ('skipped-' + item['group'] if row[4] == 'not-run' else 'fail(' + row[4] + ')')
        results.append(shared.Result(path=item['path'], group=item['group'], reason=item['reason'],
                                    compile_status=compile_status, run_status=run_status,
                                    compile_seconds='', run_seconds='', output='',
                                    compile_log=Path(os.path.relpath(args.outdir / item['batch'] / 'LOG' / log_name(item['id'], 'compile'), args.report_dir)).as_posix(),
                                    run_log=Path(os.path.relpath(args.outdir / item['batch'] / 'LOG' / log_name(item['id'], 'run'), args.report_dir)).as_posix(),
                                    compile_directory=''))
    args.report_dir.mkdir(parents=True, exist_ok=True)
    shared.write_csv(results, args.report_dir / 'results.csv')
    shared.write_report(results, args.report_dir / 'report.md', args)
    failed = [result for result in results if result.group == 'self-contained' and
              result.compile_status != 'pending' and
              (result.compile_status != 'pass' or result.run_status != 'pass')]
    run_failures = [r for r in results if r.run_status.startswith('fail')]
    complete = len(records) == len(entries)
    passed = complete and not failed and not run_failures
    summary = {'expected': len(entries), 'recorded': len(records),
               'pending': len(entries) - len(records), 'complete': complete,
               'self_contained_failures': len(failed), 'run_failures': len(run_failures),
               'compile_status': shared.count_by(results, 'compile_status'),
               'run_status': shared.count_by(results, 'run_status'), 'passed': passed}
    (args.report_dir / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(summary), flush=True)
    return passed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--outdir', type=Path, default=ROOT / 'out/msdos/exampleageddon')
    parser.add_argument('--report-dir', type=Path)
    parser.add_argument('--package', type=Path, required=True)
    parser.add_argument('--dosbox', type=Path, required=True)
    parser.add_argument('--sdk', type=Path)
    parser.add_argument('--core', choices=('normal', 'dynamic_x86'), default='normal')
    parser.add_argument('--batch-size', type=int, default=40)
    parser.add_argument('--compile-timeout', type=int, default=600)
    parser.add_argument('--run-timeout', type=int, default=180)
    parser.add_argument('--max-output-bytes', type=int, default=2 * 1024 * 1024)
    parser.add_argument('--resume', action='store_true')
    parser.add_argument('--keep-work', action='store_true')
    parser.add_argument('--max-batches', type=int, default=0, help='development bound; incomplete runs never pass')
    parser.add_argument('--start-batch', type=int, default=0,
                        help='process this batch first, then wrap through the full inventory')
    args = parser.parse_args()
    for name in ('root', 'package', 'dosbox'):
        setattr(args, name, getattr(args, name).resolve(strict=True))
    if args.sdk:
        args.sdk = args.sdk.resolve(strict=True)
    args.outdir = args.outdir.resolve()
    args.report_dir = (args.report_dir or args.outdir / 'reports').resolve()
    if min(args.batch_size, args.compile_timeout, args.run_timeout, args.max_output_bytes) <= 0 or args.max_batches < 0:
        parser.error('batch size and bounds must be positive')
    if not all((args.package / name).is_file() for name in
               ('fb/fbc.exe', 'djgpp/bin/CWSDPMI.EXE')):
        parser.error('a complete DOS package with FBC and CWSDPMI is required')
    sources = sorted(path for path in (args.root / 'examples').rglob('*.bas') if path.is_file())
    if not sources:
        parser.error('example inventory is empty')
    try:
        starts = batch_starts(len(sources), args.batch_size, args.start_batch)
    except ValueError as error:
        parser.error(str(error))
    entries = []
    for index, path in enumerate(sources):
        classification = shared.classify(path, args.root, 'dos', False)
        entries.append({'id': f'{index:04d}', 'path': path.relative_to(args.root).as_posix(),
                        'group': classification.group, 'reason': classification.reason,
                        'runnable': classification.runnable, 'batch': f'B{index // args.batch_size:03d}'})
    print(f'Fingerprinting {len(entries)} examples and DOS package inputs', flush=True)
    identity = {'examples': fingerprint(args.root / 'examples'), 'includes': fingerprint(args.root / 'inc'),
                'package': fingerprint(args.package), 'emulator': guest.sha256(args.dosbox),
                'sdk': fingerprint(args.sdk) if args.sdk else None, 'core': args.core,
                'batch_size': args.batch_size, 'compile_timeout': args.compile_timeout,
                'run_timeout': args.run_timeout, 'max_output_bytes': args.max_output_bytes,
                'runner': guest.sha256(Path(__file__)),
                'guest_runner': guest.sha256(ROOT / 'build_scripts/dos-run-program.py'),
                'preflight_source': guest.sha256(ROOT / 'tests/dos/emulator-x87.bas'),
                'shared_runner': guest.sha256(ROOT / 'build_scripts/exampleageddon-freebasic.py')}
    manifest = args.outdir / 'manifest.json'
    if manifest.exists():
        old = json.loads(manifest.read_text())
        if not args.resume or old['identity'] != identity or old['entries'] != entries:
            parser.error('existing results require --resume and identical source/tool inputs')
    else:
        args.outdir.mkdir(parents=True, exist_ok=True)
        manifest.write_text(json.dumps({'identity': identity, 'entries': entries}, indent=2) + '\n', encoding='utf-8')
    # The shared report writer needs these descriptions, not a host compiler.
    args.fbc = [str(args.package / 'fb/fbc.exe')]
    args.target_os, args.no_run = 'dos', False
    records = {}
    completed_batches = 0
    for start in starts:
        items = entries[start:start + args.batch_size]
        batch = args.outdir / items[0]['batch']
        batch.mkdir(exist_ok=True)
        rows = read_rows(batch, items)
        done = (batch / 'DONE.TXT').read_text().strip() if (batch / 'DONE.TXT').exists() else ''
        if len(rows) != len(items) or done != f'DONE={len(items)}':
            if args.max_batches and completed_batches >= args.max_batches:
                continue
            rows = execute_batch(batch, items, args)
            completed_batches += 1
        records.update(rows)
        receipt_path = batch / 'receipt.json'
        artifacts = json.loads(receipt_path.read_text()).get('artifacts', {}) if receipt_path.exists() else {}
        artifacts.update({p.name: guest.sha256(p) for p in (batch / 'BIN').glob('*') if p.is_file()})
        receipt_path.write_text(json.dumps({'rows': list(rows.values()), 'artifacts': artifacts}, indent=2) + '\n')
        if not args.keep_work:
            for name in ('WORK', 'BIN', 'TMP'):
                target = (batch / name).resolve()
                if target.parent != batch.resolve():
                    raise ValueError('cleanup path escapes owned DOS batch')
                if target.exists():
                    shutil.rmtree(target)
        write_reports(entries, records, args)
    return 0 if write_reports(entries, records, args) else 1


if __name__ == '__main__':
    raise SystemExit(main())

